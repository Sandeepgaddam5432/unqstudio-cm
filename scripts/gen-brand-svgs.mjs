// Dev-time generator → src/ui/icons/brandSvgs.ts (Layer 1 of the icon system).
// Reads the MONO (currentColor) glyphs from the devDependency @lobehub/icons-static-svg and inlines only the ~35 brands we use,
// so the runtime bundle carries no icon package and icons render instantly + offline. Re-run: `node scripts/gen-brand-svgs.mjs`.
import { readFileSync, writeFileSync } from 'node:fs'

const DIR = 'node_modules/@lobehub/icons-static-svg/icons'
/** brand key → upstream file slug */
const MAP = {
  openai: 'openai', anthropic: 'anthropic', claude: 'claude', google: 'google', gemini: 'gemini', moonshot: 'moonshot', kimi: 'kimi',
  deepseek: 'deepseek', openrouter: 'openrouter', groq: 'groq', xai: 'xai', mistral: 'mistral', meta: 'meta', qwen: 'qwen', cohere: 'cohere',
  perplexity: 'perplexity', together: 'together', fireworks: 'fireworks', cerebras: 'cerebras', ollama: 'ollama', lmstudio: 'lmstudio',
  huggingface: 'huggingface', github: 'github', deepinfra: 'deepinfra', venice: 'venice', vercel: 'vercel', nvidia: 'nvidia',
  sambanova: 'sambanova', zhipu: 'zhipu', minimax: 'minimax', yi: 'yi', novita: 'novita', hyperbolic: 'hyperbolic', siliconflow: 'siliconcloud',
}
// Hand-drawn neutral glyph (sliders) for user-defined providers.
const CUSTOM = '<path d="M4 7h9M17 7h3M4 17h3M11 17h9M13 4v6M7 14v6" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round"/>'
const out = {}
for (const [key, slug] of Object.entries(MAP)) {
  const svg = readFileSync(`${DIR}/${slug}.svg`, 'utf8')
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>[\s\S]*?<\/title>/g, '')
  if (!inner.trim()) throw new Error('empty glyph ' + slug)
  out[key] = inner.trim()
}
out.custom = CUSTOM
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')
writeFileSync('src/ui/icons/brandSvgs.ts', `// GENERATED by scripts/gen-brand-svgs.mjs — do not edit. Inner markup of 24×24 mono (currentColor) brand glyphs.\n// Source: @lobehub/icons-static-svg (MIT). Layer 1 of the zero-broken-icon system: bundled, instant, offline.\nexport const BRAND_SVGS: Record<string, string> = {\n${body}\n}\nexport type BrandKey = ${Object.keys(out).map((k) => `'${k}'`).join(' | ')}\nexport const BRAND_KEYS = Object.keys(BRAND_SVGS) as BrandKey[]\n`)
console.log('✓ brandSvgs.ts', Object.keys(out).length, 'glyphs')
