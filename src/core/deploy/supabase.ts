import { DeployError, api } from './common'

export interface Column { name: string; type: string; format?: string; required: boolean; pk: boolean }
export interface Table { name: string; columns: Column[] }

export async function fetchOpenApi(url: string, key: string, f: typeof fetch = fetch) {
  return api<any>(f, 'Supabase', `${url.replace(/\/+$/, '')}/rest/v1/`, { headers: { apikey: key, Authorization: `Bearer ${key}`, Accept: 'application/openapi+json, application/json' } })
}

export function parseTables(spec: any): Table[] {
  const defs = spec?.definitions ?? spec?.components?.schemas ?? {}
  return Object.entries<any>(defs).map(([name, d]) => {
    const req: string[] = d.required ?? []
    return {
      name,
      columns: Object.entries<any>(d.properties ?? {}).map(([c, p]) => ({
        name: c, type: p.type ?? 'string', format: p.format, required: req.includes(c), pk: /Primary Key/i.test(p.description ?? ''),
      })),
    }
  }).sort((a, b) => a.name.localeCompare(b.name))
}

export function tsType(c: Pick<Column, 'type' | 'format'>): string {
  if (/json/i.test(c.format ?? '')) return 'Json'
  switch (c.type) {
    case 'integer': case 'number': return 'number'
    case 'boolean': return 'boolean'
    case 'array': return 'unknown[]'
    case 'object': return 'Json'
    default: return 'string'
  }
}

const pascal = (s: string) => s.replace(/(^|[_\s-]+)(\w)/g, (_, __, c: string) => c.toUpperCase())

export function generateTypes(tables: Table[]): string {
  const lines = ['// Generated by UnQStudio from your Supabase REST schema.', 'export type Json = string | number | boolean | null | { [key: string]: Json } | Json[]', '']
  for (const t of tables) {
    lines.push(`export interface ${pascal(t.name)} {`)
    for (const c of t.columns) lines.push(`  ${/^[a-zA-Z_]\w*$/.test(c.name) ? c.name : JSON.stringify(c.name)}${c.required ? '' : '?'}: ${tsType(c)}${c.required ? '' : ' | null'}`)
    lines.push('}', '')
  }
  lines.push('export interface Database {', '  public: {', '    Tables: {')
  for (const t of tables) lines.push(`      ${/^[a-zA-Z_]\w*$/.test(t.name) ? t.name : JSON.stringify(t.name)}: { Row: ${pascal(t.name)}; Insert: Partial<${pascal(t.name)}>; Update: Partial<${pascal(t.name)}>; Relationships: [] }`)
  lines.push('    }', '    Views: Record<string, never>', '    Functions: Record<string, never>', '  }', '}', '')
  return lines.join('\n')
}

export function jwtRole(key: string): string | null {
  try {
    const part = key.split('.')[1]
    return JSON.parse(atob(part.replace(/-/g, '+').replace(/_/g, '/'))).role ?? null
  } catch { return null }
}

export function clientSnippet(url: string, key: string): Record<string, string> {
  if (jwtRole(key) === 'service_role') throw new DeployError('This is a service_role key. Never embed it in browser code — use the public anon key for the generated client.')
  const clean = url.replace(/\/+$/, '')
  return {
    '/src/lib/supabase.ts':
`import { createClient } from '@supabase/supabase-js'
import type { Database } from './database.types'

// The anon key is public by design; protect data with Row Level Security policies.
const url = (import.meta.env.VITE_SUPABASE_URL as string | undefined) ?? '${clean}'
const anonKey = (import.meta.env.VITE_SUPABASE_ANON_KEY as string | undefined) ?? '${key}'

export const supabase = createClient<Database>(url, anonKey)
`,
    '/.env.example': `VITE_SUPABASE_URL=${clean}\nVITE_SUPABASE_ANON_KEY=your-anon-key\n`,
  }
}

export async function browseTable(url: string, key: string, table: string, limit = 20, f: typeof fetch = fetch): Promise<Record<string, unknown>[]> {
  return api(f, 'Supabase', `${url.replace(/\/+$/, '')}/rest/v1/${encodeURIComponent(table)}?select=*&limit=${limit}`, { headers: { apikey: key, Authorization: `Bearer ${key}` } })
}
