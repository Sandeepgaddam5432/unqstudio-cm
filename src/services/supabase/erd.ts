/** Visual schema designer core: model → Postgres SQL (+ RLS owner policies, Realtime), seed SQL, migration path, destructive-SQL detector. */
export interface Column { name: string; type: string; pk?: boolean; notNull?: boolean; unique?: boolean; default?: string; references?: { table: string; column: string; onDelete?: 'cascade' | 'set null' | 'restrict' } }
export interface Table { name: string; columns: Column[]; rls?: 'owner' | 'none'; ownerColumn?: string; realtime?: boolean }
export interface SchemaModel { tables: Table[] }
export const SQL_TYPES = ['uuid', 'text', 'int4', 'int8', 'numeric', 'bool', 'timestamptz', 'date', 'jsonb', 'float8'] as const
const IDENT = /^[a-z_][a-z0-9_]*$/i
const q = (id: string) => { if (!IDENT.test(id)) throw new Error(`Invalid SQL identifier: ${id}`); return `"${id}"` }
const TYPE_OK = new RegExp(`^(${SQL_TYPES.join('|')})$`)
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`

export function validateModel(m: SchemaModel): string[] {
  const errs: string[] = []
  const names = new Set<string>()
  for (const t of m.tables) {
    if (!IDENT.test(t.name)) errs.push(`Table "${t.name}": invalid name`)
    if (names.has(t.name)) errs.push(`Duplicate table "${t.name}"`)
    names.add(t.name)
    if (!t.columns.some((c) => c.pk)) errs.push(`Table "${t.name}" has no primary key`)
    for (const c of t.columns) {
      if (!IDENT.test(c.name)) errs.push(`${t.name}.${c.name}: invalid column name`)
      if (!TYPE_OK.test(c.type)) errs.push(`${t.name}.${c.name}: unsupported type "${c.type}"`)
      if (c.references && !m.tables.some((x) => x.name === c.references!.table && x.columns.some((y) => y.name === c.references!.column))) errs.push(`${t.name}.${c.name}: references missing ${c.references.table}.${c.references.column}`)
    }
    if (t.rls === 'owner' && !t.columns.some((c) => c.name === (t.ownerColumn ?? 'user_id'))) errs.push(`Table "${t.name}": owner RLS needs a "${t.ownerColumn ?? 'user_id'}" column`)
  }
  return errs
}
/** Tables ordered so every referenced table comes first. */
export function topoOrder(m: SchemaModel): Table[] {
  const out: Table[] = []; const seen = new Set<string>()
  const visit = (t: Table, stack: string[]) => {
    if (seen.has(t.name) || stack.includes(t.name)) return
    for (const c of t.columns) { const ref = c.references && m.tables.find((x) => x.name === c.references!.table); if (ref && ref !== t) visit(ref, [...stack, t.name]) }
    seen.add(t.name); out.push(t)
  }
  m.tables.forEach((t) => visit(t, []))
  return out
}
export function generateSql(m: SchemaModel): string {
  const errs = validateModel(m)
  if (errs.length) throw new Error(errs.join('; '))
  const out: string[] = ['-- Generated by UnQStudio Schema Designer']
  for (const t of topoOrder(m)) {
    const pks = t.columns.filter((c) => c.pk).map((c) => q(c.name))
    const cols = t.columns.map((c) => `  ${q(c.name)} ${c.type}${c.notNull || c.pk ? ' not null' : ''}${c.unique ? ' unique' : ''}${c.default ? ` default ${c.default}` : c.pk && c.type === 'uuid' ? ' default gen_random_uuid()' : ''}${c.references ? ` references ${q(c.references.table)}(${q(c.references.column)}) on delete ${c.references.onDelete ?? 'cascade'}` : ''}`)
    out.push(`\ncreate table if not exists public.${q(t.name)} (\n${cols.join(',\n')},\n  primary key (${pks.join(', ')})\n);`)
    if (t.rls === 'owner') {
      const o = q(t.ownerColumn ?? 'user_id'); const tn = `public.${q(t.name)}`
      out.push(`alter table ${tn} enable row level security;`)
      for (const [verb, clause] of [['select', `using (auth.uid() = ${o})`], ['insert', `with check (auth.uid() = ${o})`], ['update', `using (auth.uid() = ${o}) with check (auth.uid() = ${o})`], ['delete', `using (auth.uid() = ${o})`]] as const) out.push(`create policy ${q(`${t.name}_owner_${verb}`)} on ${tn} for ${verb} to authenticated ${clause};`)
    }
    if (t.realtime) out.push(`alter publication supabase_realtime add table public.${q(t.name)};`)
  }
  return out.join('\n') + '\n'
}
const uuidN = (table: number, row: number) => `00000000-0000-4000-8000-${String(table).padStart(4, '0')}${String(row).padStart(8, '0')}`
const NAMES = ['Ava Chen', 'Noah Patel', 'Mia Rossi', 'Liam Okafor', 'Zoe Martin', 'Ethan Silva']
function seedValue(c: Column, t: number, r: number, parentOf: (c: Column, r: number) => string | undefined, ownerCol?: string): string {
  if (ownerCol && c.name === ownerCol && c.type === 'uuid' && !c.references) return lit('00000000-0000-4000-8000-000000000000') // placeholder owner: replace with a real auth.users id before running
  const ref = parentOf(c, r); if (ref) return lit(ref)
  const n = c.name.toLowerCase()
  if (c.type === 'uuid') return lit(uuidN(t, r))
  if (c.type === 'bool') return r % 2 === 0 ? 'true' : 'false'
  if (/int|numeric|float/.test(c.type)) return /price|amount|total|cost/.test(n) ? String(((r + 1) * 12.5).toFixed(2)) : String(r + 1)
  if (c.type === 'timestamptz') return `now() - interval '${r} days'`
  if (c.type === 'date') return `current_date - ${r}`
  if (c.type === 'jsonb') return `'{}'::jsonb`
  if (/email/.test(n)) return lit(`${NAMES[r % NAMES.length].split(' ')[0].toLowerCase()}${r}@example.com`)
  if (/name/.test(n)) return lit(NAMES[r % NAMES.length])
  if (/title|subject/.test(n)) return lit(`Sample ${n} ${r + 1}`)
  if (/desc|body|content|note/.test(n)) return lit(`Realistic ${n} text for row ${r + 1}.`)
  return lit(`${c.name} ${r + 1}`)
}
/** Deterministic realistic seed SQL; FK columns point at earlier tables' seeded ids. Owner columns get a placeholder uuid — replace it with a real auth.users id. */
export function generateSeedSql(m: SchemaModel, rows = 5): string {
  const errs = validateModel(m); if (errs.length) throw new Error(errs.join('; '))
  const ordered = topoOrder(m)
  const idx = new Map(ordered.map((t, i) => [t.name, i + 1]))
  const out = ['-- Seed data (idempotent: re-running skips existing ids)']
  for (const t of ordered) {
    const ti = idx.get(t.name)!
    const cols = t.columns
    const parentOf = (c: Column, r: number) => { if (!c.references) return undefined; const p = idx.get(c.references.table)!; const pt = m.tables.find((x) => x.name === c.references!.table)!; const pk = pt.columns.find((x) => x.name === c.references!.column)!; return pk.type === 'uuid' ? uuidN(p, r % rows) : undefined }
    const values = Array.from({ length: rows }, (_, r) => `(${cols.map((c) => seedValue(c, ti, r, parentOf, t.rls === 'owner' ? (t.ownerColumn ?? 'user_id') : undefined)).join(', ')})`)
    const pk = t.columns.filter((c) => c.pk).map((c) => q(c.name)).join(', ')
    out.push(`insert into public.${q(t.name)} (${cols.map((c) => q(c.name)).join(', ')}) values\n  ${values.join(',\n  ')}\non conflict (${pk}) do nothing;`)
  }
  return out.join('\n') + '\n'
}
export const migrationPath = (n: number, name: string) => `/supabase/migrations/${String(n).padStart(4, '0')}_${name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '') || 'schema'}.sql`
/** Destructive statements that must trigger the permission card before running. */
export const isDestructiveSql = (sql: string): boolean => /\b(drop\s+(table|schema|column|policy|database)|truncate\b|delete\s+from\b(?![\s\S]*\bwhere\b))/i.test(sql.replace(/--.*$/gm, ''))
