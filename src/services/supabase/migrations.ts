export interface ColumnSpec { name: string; type: string; notNull?: boolean; default?: string }

const SAFE_IDENT = /^[a-z_][a-z0-9_]{0,62}$/
const SAFE_TYPE = /^(text|uuid|int|integer|bigint|smallint|boolean|bool|numeric|real|double precision|date|timestamptz|timestamp|jsonb|json)$/i
export const ident = (s: string): string => { const v = s.trim().toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^(\d)/, '_$1'); if (!SAFE_IDENT.test(v)) throw new Error(`Invalid identifier “${s}”`); return v }

/** Parse "title text, done boolean, qty int not null" → column specs. */
export function parseColumnSpec(spec: string): ColumnSpec[] {
  return spec.split(/[,\n]/).map((l) => l.trim()).filter(Boolean).map((l) => {
    const [name, type = 'text', ...rest] = l.split(/\s+/)
    if (!SAFE_TYPE.test(type)) throw new Error(`Unsupported column type “${type}”. Use text, uuid, int, bigint, boolean, numeric, date, timestamptz, jsonb.`)
    const tail = rest.join(' ').toLowerCase()
    return { name: ident(name!), type: type.toLowerCase(), notNull: /not\s+null/.test(tail) }
  })
}

/** `create table` + owner-only Row Level Security + Realtime publication. */
export function createTableSql(table: string, cols: ColumnSpec[], opts: { ownerColumn?: boolean } = { ownerColumn: true }): string {
  const t = ident(table)
  const body = [
    '  id uuid primary key default gen_random_uuid()',
    ...(opts.ownerColumn !== false ? ['  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade'] : []),
    ...cols.map((c) => `  ${ident(c.name)} ${c.type}${c.notNull ? ' not null' : ''}${c.default ? ` default ${c.default}` : ''}`),
    '  created_at timestamptz not null default now()',
  ].join(',\n')
  const rls = opts.ownerColumn !== false ? `
alter table public.${t} enable row level security;
create policy "${t}: owner can read" on public.${t} for select using (auth.uid() = user_id);
create policy "${t}: owner can insert" on public.${t} for insert with check (auth.uid() = user_id);
create policy "${t}: owner can update" on public.${t} for update using (auth.uid() = user_id);
create policy "${t}: owner can delete" on public.${t} for delete using (auth.uid() = user_id);
` : `\nalter table public.${t} enable row level security;\ncreate policy "${t}: public read" on public.${t} for select using (true);\n`
  return `-- Generated by UnQStudio\ncreate table if not exists public.${t} (\n${body}\n);\n${rls}\nalter publication supabase_realtime add table public.${t};\n`
}

export const defaultMigration = (table = 'notes'): string => createTableSql(table, [{ name: 'title', type: 'text', notNull: true }, { name: 'done', type: 'boolean', default: 'false' }])

/** `https://abcd.supabase.co` → `abcd` (the project ref) or null. */
export const projectRef = (url: string): string | null => /^https?:\/\/([a-z0-9]+)\.supabase\.(?:co|in|net)/i.exec(url.trim())?.[1] ?? null

/** Run SQL through the Supabase Management API (needs a personal access token `sbp_…`; browsers may block it with CORS → fall back to the SQL editor). */
export async function runSql(url: string, accessToken: string, sql: string, f: typeof fetch = fetch): Promise<{ ok: boolean; message: string }> {
  const ref = projectRef(url)
  if (!ref) return { ok: false, message: 'Could not derive the project ref from the Supabase URL.' }
  try {
    const r = await f(`https://api.supabase.com/v1/projects/${ref}/database/query`, { method: 'POST', headers: { Authorization: `Bearer ${accessToken}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ query: sql }) })
    if (r.ok) return { ok: true, message: 'Migration applied.' }
    return { ok: false, message: `Supabase returned ${r.status}: ${(await r.text()).slice(0, 200)}` }
  } catch {
    return { ok: false, message: 'The browser blocked the request (CORS). Copy the SQL and run it in the Supabase SQL editor.' }
  }
}
export const sqlEditorUrl = (url: string): string => { const ref = projectRef(url); return ref ? `https://supabase.com/dashboard/project/${ref}/sql/new` : 'https://supabase.com/dashboard' }
